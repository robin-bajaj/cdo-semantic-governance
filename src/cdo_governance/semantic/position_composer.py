"""Generate a lossless CDO-owned semantic catalog from validated team implementations.

The output is custom federation metadata, NOT native dbt semantic-model YAML.
Only compiled (post-inheritance) team definitions and a dbt manifest are accepted.
"""
import argparse
from copy import deepcopy
from pathlib import Path
import yaml

from ..validation.contract_validator import validate_cdo_contract
from .contract_registry import resolve_contract
from .composition_selection import select_composition, available_implementations


def _load(path):
    value = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"{path}: expected YAML mapping")
    return value


def _contract_meta(node):
    cfg = node.get("config") or {}
    return (cfg.get("meta") or node.get("meta") or {}).get("semantic_contract") or {}


def _compiled_models(project):
    """Index compiled YAML models; reject ambiguous duplicate dbt model names."""
    by_name = {}
    for path in sorted((Path(project) / "models").rglob("*.yml")) + sorted((Path(project) / "models").rglob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if not isinstance(data, dict):
            raise ValueError(f"{path}: expected YAML mapping")
        for model in data.get("models") or []:
            name = model.get("name")
            if not name or name in by_name:
                raise ValueError(f"{path}: missing or duplicate model name {name}")
            by_name[name] = (model, path)
    return by_name


def compose_cdo(project_path, contract_path, manifest_path, output_path,
                expected_teams=None, bindings_path=None, selection_path=None,
                discovery_path=None):
    """Validate before producing one deterministic, versioned YAML catalog.

    manifest is generated by dbt parse from the *same compiled project*.
    expected_teams prevents partial catalogs if a participating team vanishes.
    This generator does not create SQL or a dbt-native combined semantic model.
    """
    project_path, output_path = Path(project_path), Path(output_path)
    # Compose against the same fully resolved Position contract as the compiler.
    contract = resolve_contract(contract_path, 'cdo.position', 1)
    manifest = _load(manifest_path)
    bindings = _load(bindings_path) if bindings_path is not None else None
    problems = validate_cdo_contract(manifest, contract, bindings)
    if problems:
        raise ValueError("CDO contract validation failed:\n" + "\n".join(problems))

    compiled = _compiled_models(project_path)
    implementations = []
    metric_names = set()
    seen_semantics = set()
    required = {c["name"]: c for c in contract["attributes"]}
    for node in sorted((manifest.get("nodes") or {}).values(), key=lambda n: n.get("unique_id", "")):
        if node.get("resource_type") != "model":
            continue
        bound = ((bindings or {}).get("models") or {}).get(node.get("name"), {})
        marker = bound.get("semantic_contract") if bindings is not None else _contract_meta(node)
        if (marker or {}).get("implements") != contract["name"]:
            continue
        name = node["name"]
        if name not in compiled:
            raise ValueError(f"Compiled YAML not found for validated model {name}")
        model, path = compiled[name]
        if bindings is None:
            source_marker = _contract_meta(model)
            if source_marker != marker:
                raise ValueError(f"{name}: compiled YAML contract marker differs from manifest")
        elif (model.get("config") or {}).get("meta", {}).get("semantic_contract"):
            raise ValueError(f"{name}: deployable YAML must not contain CDO contract metadata")
        semantic = model.get("semantic_model") or {}
        if not semantic.get("enabled") or not semantic.get("name"):
            raise ValueError(f"{name}: missing enabled, named semantic_model")
        if semantic["name"] in seen_semantics:
            raise ValueError(f"Duplicate semantic model name: {semantic['name']}")
        seen_semantics.add(semantic["name"])
        included = marker.get("included_attributes")
        if (not isinstance(included, list) or not included or
                len(included) != len(set(included)) or set(included) - set(required)):
            raise ValueError(f"{name}: invalid selected business attributes")
        columns = model.get("columns") or []
        col_map = {c["name"]: c for c in columns}
        if len(col_map) != len(columns):
            raise ValueError(f"{name}: duplicate compiled columns")
        for field in included:
            if field not in col_map:
                raise ValueError(f"{name}: missing compiled CDO attribute {field}")
            expected_type = required[field]["data_type"]
            if col_map[field].get("data_type") != expected_type:
                raise ValueError(f"{name}: incorrect type for included attribute {field}")
        # Entity and dimension roles are intentionally *team-owned*, never
        # inferred from the business attribute dictionary.
        metrics = model.get("metrics") or []
        for m in metrics:
            if not m.get("name") or m["name"] in metric_names:
                raise ValueError(f"Duplicate/missing metric name: {m.get('name')}")
            metric_names.add(m["name"])
        inherited_metric_names = set()
        metric_bindings = bound.get("metric_contracts", {}) if bindings is not None else None
        if metric_bindings is not None:
            if not isinstance(metric_bindings, dict):
                raise ValueError(f"{name}: invalid inherited metric bindings")
            unknown_aliases = set(metric_bindings) - {m["name"] for m in metrics}
            if unknown_aliases:
                raise ValueError(f"{name}: missing inherited metrics {sorted(unknown_aliases)}")
        for m in metrics:
            meta = (metric_bindings.get(m["name"]) if metric_bindings is not None
                    else ((m.get("config") or {}).get("meta") or {}).get("metric_contract"))
            if meta:
                inherited_metric_names.add(meta.get("implements"))
                parent = next((p for p in contract.get("metrics") or [] if p["name"] == meta.get("implements")), None)
                if parent is None or str(meta.get("version")) != str(contract["version"]):
                    raise ValueError(f"{name}: unknown inherited metric contract")
                for prop in ("type", "agg", "expr", "fill_nulls_with"):
                    if m.get(prop) != parent.get(prop):
                        raise ValueError(f"{name}: inherited metric {m['name']} overrides {prop}")
        expected_metrics = {m["name"] for m in contract.get("metrics") or []}
        opted_metric_names = set(marker.get("included_metrics") or [])
        if inherited_metric_names != opted_metric_names or inherited_metric_names - expected_metrics:
            raise ValueError(f"{name}: inherited metrics do not match selected metric aliases")

        owner = (model.get("config") or {}).get("group") or name
        implementations.append({
            "source_model": name,
            "semantic_model": semantic["name"],
            "owner": owner,
            "source_definition": str(path.relative_to(project_path)),
            "included_attributes": deepcopy(included),
            "agg_time_dimension": model.get("agg_time_dimension"),
            "columns": deepcopy(columns),
            "metrics": deepcopy(metrics),
        })
    if not implementations:
        raise ValueError("No compiled semantic implementations found")
    if expected_teams:
        missing = set(expected_teams) - {i["semantic_model"] for i in implementations}
        if missing:
            raise ValueError(f"Missing expected semantic models: {sorted(missing)}")
    result = {
        "catalog_format": "cdo-federated-semantic-catalog/v1",
        "name": "cdo_enterprise_positions",
        "contract": {"name": contract["name"], "version": contract["version"]},
        "contract_lineage": deepcopy(contract.get("lineage") or []),
        "owner": contract.get("owner", "CDO"),
        "description": "Composed semantic catalog; execution/routing must be implemented separately.",
        "common_attributes": [field for field in required if any(field in entry["included_attributes"] for entry in implementations)],
        "attribute_definitions": deepcopy(contract["attributes"]),
        "metric_definitions": deepcopy(contract.get("metrics") or []),
        "implementations": implementations,
    }
    if discovery_path is not None:
        discovery = Path(discovery_path)
        discovery.parent.mkdir(parents=True, exist_ok=True)
        discovery.write_text(yaml.safe_dump(available_implementations(result), sort_keys=False), encoding='utf-8')
    if selection_path is not None:
        result = select_composition(result, selection_path)
    # Never overwrite project-authored semantic definitions.
    if output_path.resolve().is_relative_to((project_path / "models").resolve()):
        raise ValueError("Output must not be inside the dbt models directory")
    rendered = yaml.safe_dump(result, sort_keys=False, allow_unicode=True, width=100)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(rendered, encoding="utf-8")
    return output_path


def main():
    parser = argparse.ArgumentParser(description="Compose validated team semantics into a custom CDO catalog")
    parser.add_argument("--project", type=Path, required=True)
    parser.add_argument("--contract", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--require-semantic-model", action="append", dest="expected_teams")
    parser.add_argument("--bindings", type=Path, help="Ephemeral compiler-resolved CDO bindings")
    parser.add_argument("--selection", type=Path, help="Approved CDO composition selection YAML")
    parser.add_argument("--discovery-output", type=Path, help="List validated implementations and their fields")
    args = parser.parse_args()
    path = compose_cdo(args.project, args.contract, args.manifest, args.output,
                       args.expected_teams, args.bindings, args.selection, args.discovery_output)
    print(f"Generated CDO semantic catalog: {path}")


if __name__ == "__main__":
    main()
